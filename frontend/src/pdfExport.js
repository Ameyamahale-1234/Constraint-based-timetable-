import { jsPDF } from "jspdf";
import { autoTable } from "jspdf-autotable";
import { DAY_NAMES, buildSheet, entryLines, headerFields, rowsFor } from "./sheetModel";

const INK = [17, 28, 50];
const HEAD = [221, 231, 248];
const TIME_BG = [238, 243, 251];
const LUNCH_BG = [253, 243, 205];
const THEORY_BG = [239, 245, 255];
const LAB_BG = [236, 252, 241];
const CLOSED_BG = [244, 245, 247];

function cellText(cell, view, result) {
  if (!cell.open && !cell.entries.length) return "—";
  return cell.entries
    .map(({ row, continued }) => continued
      ? `(contd.) ${row.courseType === "LAB" ? `${row.courseName} (${row.batch})` : row.courseName}`
      : entryLines(row, view, result).join("\n"))
    .join("\n\n");
}

function drawPage(doc, result, view, value, meta) {
  const pageWidth = doc.internal.pageSize.getWidth();
  const margin = 28;

  doc.setFont("helvetica", "bold");
  doc.setFontSize(20);
  doc.setTextColor(...INK);
  doc.text("Class Timetable", pageWidth / 2, 40, { align: "center" });
  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.setTextColor(90, 100, 120);
  doc.text(result.collegeName || "", pageWidth / 2, 56, { align: "center" });

  const fields = headerFields(result, view, value, meta);
  // Wider space for long values (department, teacher name); every value stays on one line.
  const weights = fields.map(([label]) => (["Department", "Teacher"].includes(label) ? 2 : 1));
  const unit = (pageWidth - margin * 2) / weights.reduce((a, b) => a + b, 0);
  let x = margin;
  fields.forEach(([label, text], i) => {
    const slot = weights[i] * unit;
    doc.setFont("helvetica", "bold");
    doc.setFontSize(10);
    doc.setTextColor(...INK);
    doc.text(`${label}:`, x, 80);
    const valueX = x + doc.getTextWidth(`${label}:`) + 5;
    const room = x + slot - 14 - valueX;
    doc.setFont("helvetica", "normal");
    let size = 10, value = String(text);
    doc.setFontSize(size);
    while (doc.getTextWidth(value) > room && size > 7) doc.setFontSize(--size);
    while (doc.getTextWidth(value) > room && value.length > 4) value = value.slice(0, -2).trimEnd() + "…";
    doc.text(value, valueX, 80);
    doc.setDrawColor(150, 160, 180);
    doc.line(valueX - 2, 84, x + slot - 14, 84);
    x += slot;
  });

  const sheet = buildSheet(result, rowsFor(result, view, value));
  // Stretch period rows to use the page height (rows still grow if a cell needs more room).
  const periodRows = sheet.rows.filter(r => r.type === "period").length;
  const usable = doc.internal.pageSize.getHeight() - 96 - 24 - 20 - 40;
  const rowHeight = Math.max(30, Math.floor(usable / Math.max(1, periodRows)));
  const head = [["Time", ...sheet.days.map(d => DAY_NAMES[d] || d)]];
  const body = sheet.rows.map(r => r.type === "lunch"
    ? [{ content: `${r.start} – ${r.end}`, styles: { fillColor: TIME_BG, fontStyle: "bold" } },
       { content: "LUNCH BREAK", colSpan: sheet.days.length, styles: { halign: "center", valign: "middle", fontStyle: "bold", fillColor: LUNCH_BG, textColor: [120, 85, 10] } }]
    : [{ content: `${r.start} – ${r.end}`, styles: { fillColor: TIME_BG, fontStyle: "bold", halign: "center", valign: "middle", minCellHeight: rowHeight } },
       ...r.cells.map(cell => ({
         content: cellText(cell, view, result),
         styles: {
           fillColor: !cell.open && !cell.entries.length ? CLOSED_BG
             : cell.entries.some(e => e.row.courseType === "LAB") ? LAB_BG
             : cell.entries.length ? THEORY_BG : [255, 255, 255],
           textColor: !cell.open && !cell.entries.length ? [170, 175, 185] : INK,
           halign: !cell.open && !cell.entries.length ? "center" : "left",
           valign: !cell.open && !cell.entries.length ? "middle" : "top"
         }
       }))]);

  autoTable(doc, {
    head, body,
    startY: 98,
    rowPageBreak: "avoid",
    margin: { left: margin, right: margin },
    theme: "grid",
    styles: { font: "helvetica", fontSize: 7, cellPadding: 4, lineColor: [190, 200, 215], lineWidth: 0.6, textColor: INK, valign: "top", overflow: "linebreak" },
    headStyles: { fillColor: HEAD, textColor: INK, fontStyle: "bold", fontSize: 9, halign: "center" },
    columnStyles: { 0: { cellWidth: 70 } }
  });

  doc.setFontSize(8);
  doc.setTextColor(140, 150, 165);
  doc.text(`Generated by ClassSync on ${new Date().toLocaleDateString()}`, margin, doc.internal.pageSize.getHeight() - 16);
}

function fileName(result, suffix) {
  return `${(result.collegeName || "timetable").replace(/[^a-z0-9]+/gi, "_")}_${suffix.replace(/[^a-z0-9]+/gi, "_")}.pdf`;
}

/** PDF of the timetable currently shown. */
export function downloadPdf(result, view, value, meta, label) {
  const doc = new jsPDF({ orientation: "landscape", unit: "pt", format: "a4" });
  drawPage(doc, result, view, value, meta);
  doc.save(fileName(result, label || "timetable"));
}

/** One PDF with a page per division. */
export function downloadAllDivisionsPdf(result, meta) {
  const doc = new jsPDF({ orientation: "landscape", unit: "pt", format: "a4" });
  (result.divisions || []).forEach((d, i) => {
    if (i > 0) doc.addPage();
    drawPage(doc, result, "division", String(d.id), meta);
  });
  doc.save(fileName(result, "all_divisions"));
}
